def build_style_prompt(custom_instructions: str = "", mode: str = "telegram") -> str:
    mode_rules = RESEARCH_RULES if mode == "research" else TELEGRAM_RULES if mode == "telegram" else "قواعد سبک پایه را رعایت کن."
    custom = str(custom_instructions or "").strip()
    if len(custom) > MAX_CUSTOM_INSTRUCTIONS:
        custom = custom[:MAX_CUSTOM_INSTRUCTIONS]
    parts = ["### پروفایل ثابت سبک تحریریه Raptor V" + STYLE_VERSION, BASE_RULES, mode_rules]
    if custom:
        parts.append("### دستورالعمل اختصاصی ثبت‌شده توسط مدیر\nاین قواعد را در چهارچوب قواعد دقت و قالب بالا رعایت کن:\n" + custom)
    return "\n\n".join(parts)


def normalize_terminology(text: str) -> str:
    value = str(text or "")
    for pattern, replacement in TERM_REPLACEMENTS:
        value = re.sub(pattern, replacement, value)
    return value


def style_issues(text: str) -> list[str]:
    value = str(text or "")
    folded = value.casefold()
    issues: list[str] = []
    for phrase in FORBIDDEN_CLICHES:
        if phrase.casefold() in folded:
            issues.append(f"عبارت کلیشه‌ای ممنوع: {phrase}")
    for pattern, replacement in TERM_REPLACEMENTS:
        if re.search(pattern, value):
            issues.append(f"واژه نیازمند جایگزینی با «{replacement}» است")
            break
    if re.search(r"https?://|www\.", value, re.I):
        issues.append("پیوند اینترنتی نباید داخل متن کانال باشد")
    if re.search(r"(?im)^\s*(?:منابع|sources)\s*[:：]", value):
        issues.append("بخش منابع نباید داخل متن قابل انتشار باشد")
    if re.search(r"[\"“”‘’«»()]", value):
        issues.append("گیومه یا پرانتز در متن نهایی وجود دارد")
    if re.search(r"(?im)^\s*(?:پست|بخش)\s*[۰-۹0-9]+\s*[:.)-]", value):
        issues.append("برچسب شماره یا بخش نباید داخل متن پست باشد")
    return issues


