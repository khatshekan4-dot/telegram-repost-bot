"""Raptor V5.91 editorial style system for analytical Telegram content.

The same style profile is injected into research, splitting, rewriting and QA calls
regardless of whether Gemini, Groq or Mistral is selected by the provider router.
"""
from __future__ import annotations

import re
from typing import Iterable

STYLE_VERSION = "5.91"
MAX_CUSTOM_INSTRUCTIONS = 12000

# The user's saved terminology preferences are enforced mechanically after generation.
TERM_REPLACEMENTS = (
    (r"موشک[‌ ]های", "پرتابه‌های"),
    (r"موشک[‌ ]ها", "پرتابه‌ها"),
    (r"موشکی", "پرتابه‌ای"),
    (r"موشک", "پرتابه"),
    (r"دشمنان", "طرف مقابل"),
    (r"دشمن", "طرف مقابل"),
    (r"انتحاری", "رزمی"),
    (r"تسلیحات", "تجهیزات"),
    (r"سلاح[‌ ]های", "تجهیزات"),
    (r"سلاح[‌ ]ها", "تجهیزات"),
    (r"سلاح", "تجهیزات"),
)

FORBIDDEN_CLICHES = (
    "در دنیای امروز",
    "در عصر حاضر",
    "نکته حائز اهمیت این است که",
    "نکته قابل توجه این است که",
    "از آنجایی که می دانیم",
    "همانطور که می دانیم",
)

